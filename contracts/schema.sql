-- Цифровые Летописи природы — схема БД (PostgreSQL 16+).
-- Источник правды: docs/SPEC.md и contracts/observation.schema.json.
-- Имена колонок совпадают с именами полей JSON Schema.
-- Скрипт идемпотентен: повторный запуск ничего не ломает и не удаляет данные.
-- Изменения схемы после первого запуска — отдельными миграциями (ALTER ...), не правкой CREATE.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- pg_trgm разбирает на триграммы только «буквы» по LC_CTYPE базы. При LC_CTYPE = C кириллица
-- игнорируется и нечёткий поиск по русским названиям молча не работает. Создавайте БД так:
--   CREATE DATABASE letopisi TEMPLATE template0 ENCODING 'UTF8' LC_COLLATE 'ru_RU.UTF-8' LC_CTYPE 'ru_RU.UTF-8';
-- (подойдут также en_US.UTF-8 / C.UTF-8 в Linux, 'ru-RU' / 'en-US' в Windows; образ postgres:16 по умолчанию — en_US.utf8).
DO $$
BEGIN
    IF show_trgm('лось') = '{}'::text[] THEN
        RAISE WARNING 'LC_CTYPE базы = %: pg_trgm не видит кириллицу, поиск по русским названиям работать не будет',
            current_setting('lc_ctype');
    END IF;
END
$$;

-- ---------------------------------------------------------------------------
-- Документы и их структура
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS documents (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           text        NOT NULL CHECK (title <> ''),
    book_no         integer     CHECK (book_no >= 1),               -- номер книги (тома); NULL — документ вне серии
    year            integer     CHECK (year BETWEEN 1800 AND 2100), -- год, за который составлена книга
    filename        text        NOT NULL,                           -- имя файла в data/raw
    format          text        NOT NULL CHECK (format IN ('pdf', 'docx', 'xlsx')),
    pages           integer     CHECK (pages >= 1),                 -- число страниц PDF; NULL для docx/xlsx
    has_text_layer  boolean     NOT NULL DEFAULT false,
    layout          text        CHECK (layout IN ('single', 'spread')), -- spread — страница PDF = разворот
    sha256          text        CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    status          text        NOT NULL DEFAULT 'queued'
                                CHECK (status IN ('queued', 'processing', 'done', 'failed', 'unsupported')),
    error           text,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sections (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     bigint  NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    parent_id       bigint  REFERENCES sections(id) ON DELETE CASCADE,
    code            text,                    -- «7.3»; NULL для ненумерованных разделов
    title           text    NOT NULL CHECK (title <> ''),
    pdf_page_from   integer CHECK (pdf_page_from >= 1),
    pdf_page_to     integer CHECK (pdf_page_to >= 1),
    CHECK (pdf_page_from IS NULL OR pdf_page_to IS NULL OR pdf_page_from <= pdf_page_to)
);

CREATE TABLE IF NOT EXISTS chunks (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     bigint  NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    section_id      bigint  REFERENCES sections(id) ON DELETE SET NULL,
    ord             integer NOT NULL CHECK (ord >= 0),
    kind            text    NOT NULL CHECK (kind IN ('page', 'paragraph', 'table', 'table_row', 'list', 'caption', 'bibliography_entry')),
    locator         jsonb   NOT NULL CHECK (jsonb_typeof(locator) = 'object'),
    text            text    NOT NULL,
    text_source     text    NOT NULL CHECK (text_source IN ('text_layer', 'ocr', 'manual')),
    ocr_confidence  real    CHECK (ocr_confidence BETWEEN 0 AND 1),
    UNIQUE (document_id, ord)
);

-- ---------------------------------------------------------------------------
-- Справочники
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS taxa (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_lat    text NOT NULL CHECK (name_lat <> ''),
    name_ru     text,
    rank        text NOT NULL DEFAULT 'species'
                CHECK (rank IN ('species', 'subspecies', 'genus', 'family', 'order', 'class')),
    genus       text,
    family      text,
    "order"     text,
    class       text,
    group_ru    text NOT NULL CHECK (group_ru IN (
                    'сосудистые растения', 'мхи', 'лишайники', 'грибы', 'птицы',
                    'млекопитающие', 'рыбы', 'амфибии и рептилии', 'насекомые',
                    'прочие беспозвоночные')),
    gbif_key    bigint,
    UNIQUE (name_lat)
);

CREATE TABLE IF NOT EXISTS taxon_names (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxon_id    bigint NOT NULL REFERENCES taxa(id) ON DELETE CASCADE,
    name        text   NOT NULL CHECK (name <> ''),
    lang        text   NOT NULL CHECK (lang IN ('ru', 'lat')),
    kind        text   NOT NULL CHECK (kind IN ('accepted', 'synonym', 'variant')),
    UNIQUE (taxon_id, name)
);

CREATE TABLE IF NOT EXISTS places (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL CHECK (name <> ''),
    category        text,
    lat             double precision CHECK (lat BETWEEN -90 AND 90),
    lon             double precision CHECK (lon BETWEEN -180 AND 180),
    coords_source   text CHECK (coords_source IN ('manual_approx', 'gazetteer', 'document')),
    UNIQUE (name),
    CHECK ((lat IS NULL) = (lon IS NULL)),
    CHECK (lat IS NULL OR coords_source IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS place_names (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    bigint NOT NULL REFERENCES places(id) ON DELETE CASCADE,
    name        text   NOT NULL CHECK (name <> ''),
    kind        text   NOT NULL CHECK (kind IN ('accepted', 'variant')),
    UNIQUE (place_id, name)
);

CREATE TABLE IF NOT EXISTS persons (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surname         text      NOT NULL CHECK (surname <> ''),
    initials        text,
    full_raw        text,
    years_active    integer[] NOT NULL DEFAULT '{}',
    year_start      integer,
    year_end        integer,
    still_working   boolean,
    UNIQUE NULLS NOT DISTINCT (surname, initials)
);

CREATE TABLE IF NOT EXISTS phenophases (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text    NOT NULL CHECK (code <> ''),
    name_ru     text,                       -- NULL — название кода не найдено в источнике
    applies_to  text    NOT NULL CHECK (applies_to IN ('plants', 'animals')),
    bbch        text,
    ord         integer NOT NULL DEFAULT 0,
    UNIQUE (applies_to, code)
);

-- ---------------------------------------------------------------------------
-- Наблюдения
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS observations (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_type         text    NOT NULL CHECK (record_type IN ('observation', 'env_measurement', 'publication')),

    -- объект
    object_type         text    NOT NULL CHECK (object_type IN ('taxon', 'phenomenon', 'env_indicator', 'publication')),
    object_raw          text    NOT NULL CHECK (object_raw <> ''),
    taxon_id            bigint  REFERENCES taxa(id) ON DELETE SET NULL,

    -- время
    date_raw            text,
    date_from           date,
    date_to             date,
    date_precision      text    CHECK (date_precision IN ('day', 'decade', 'month', 'season', 'year', 'range')),
    obs_year            integer CHECK (obs_year BETWEEN 1800 AND 2100),

    -- место
    toponym_raw         text,
    place_id            bigint  REFERENCES places(id) ON DELETE SET NULL,
    coords_raw          text,
    habitat_raw         text,

    -- событие
    event_raw           text,
    phenophase_id       bigint  REFERENCES phenophases(id) ON DELETE SET NULL,
    phenophase_raw      text,

    -- показатель
    indicator           text,
    value_num           double precision,
    value_raw           text,
    unit                text,

    -- люди (связи — в observation_persons; в API отдаются как person_ids)
    observers_raw       text,

    -- публикация (только record_type = 'publication')
    pub_authors         text,
    pub_year            integer CHECK (pub_year BETWEEN 1800 AND 2100),
    pub_title           text,
    pub_venue           text,

    -- источник
    document_id         bigint  NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    section_id          bigint  REFERENCES sections(id) ON DELETE SET NULL,
    chunk_id            bigint  REFERENCES chunks(id) ON DELETE SET NULL,
    locator             jsonb   NOT NULL CHECK (jsonb_typeof(locator) = 'object'),
    printed_pages       text,
    quote               text,
    quote_span          integer[] CHECK (quote_span IS NULL OR (
                            array_length(quote_span, 1) = 2
                            AND quote_span[1] >= 0
                            AND quote_span[1] <= quote_span[2])),
    bboxes              jsonb   NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(bboxes) = 'array'),

    -- прочее
    note                text,

    -- достоверность
    confidence          real    NOT NULL DEFAULT 0.5 CHECK (confidence BETWEEN 0 AND 1),
    flags               jsonb   NOT NULL DEFAULT '[]' CHECK (
                            jsonb_typeof(flags) = 'array'
                            AND flags <@ '["quote_not_found", "value_not_in_quote", "date_not_in_quote",
                                           "date_ambiguous", "taxon_unmatched", "taxon_ambiguous",
                                           "place_unmatched", "person_unmatched", "year_outside_book",
                                           "low_ocr", "table_parse_uncertain"]'::jsonb),
    status              text    NOT NULL DEFAULT 'auto' CHECK (status IN ('auto', 'verified', 'edited', 'rejected')),
    extractor_version   text    NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CHECK (date_from IS NULL OR date_to IS NULL OR date_from <= date_to),
    CHECK (record_type <> 'publication' OR object_type = 'publication'),
    CHECK (record_type = 'publication' OR (pub_authors IS NULL AND pub_year IS NULL
                                           AND pub_title IS NULL AND pub_venue IS NULL)),
    CHECK (quote_span IS NULL OR quote IS NOT NULL)  -- span без цитаты невозможен; цитата без span — допустимо (флаг quote_not_found)
);

CREATE TABLE IF NOT EXISTS observation_persons (
    observation_id  bigint  NOT NULL REFERENCES observations(id) ON DELETE CASCADE,
    person_id       bigint  NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
    ord             integer NOT NULL DEFAULT 0,   -- порядок в observers_raw → порядок person_ids
    PRIMARY KEY (observation_id, person_id)
);

CREATE TABLE IF NOT EXISTS observation_edits (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id  bigint NOT NULL REFERENCES observations(id) ON DELETE CASCADE,
    action          text   NOT NULL CHECK (action IN ('edit', 'verify', 'reject')),
    editor          text   NOT NULL CHECK (editor <> ''),
    changes         jsonb  NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(changes) = 'object'), -- {поле: {old, new}}
    status_before   text   NOT NULL CHECK (status_before IN ('auto', 'verified', 'edited', 'rejected')),
    status_after    text   NOT NULL CHECK (status_after  IN ('auto', 'verified', 'edited', 'rejected')),
    comment         text,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS saved_queries (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text  NOT NULL CHECK (name <> ''),
    text        text,
    filters     jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(filters) = 'object'), -- SearchFilters
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Индексы
-- ---------------------------------------------------------------------------

-- поиск по похожести (pg_trgm)
CREATE INDEX IF NOT EXISTS taxon_names_name_trgm   ON taxon_names  USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS place_names_name_trgm   ON place_names  USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS persons_surname_trgm    ON persons      USING gin (surname gin_trgm_ops);
CREATE INDEX IF NOT EXISTS observations_object_raw_trgm  ON observations USING gin (object_raw gin_trgm_ops);
CREATE INDEX IF NOT EXISTS observations_quote_trgm       ON observations USING gin (quote gin_trgm_ops);
CREATE INDEX IF NOT EXISTS observations_toponym_raw_trgm ON observations USING gin (toponym_raw gin_trgm_ops);
CREATE INDEX IF NOT EXISTS observations_observers_raw_trgm ON observations USING gin (observers_raw gin_trgm_ops);

-- фильтры
CREATE INDEX IF NOT EXISTS observations_date_from_idx     ON observations (date_from);
CREATE INDEX IF NOT EXISTS observations_date_to_idx       ON observations (date_to);
CREATE INDEX IF NOT EXISTS observations_obs_year_idx      ON observations (obs_year);
CREATE INDEX IF NOT EXISTS observations_document_id_idx   ON observations (document_id);
CREATE INDEX IF NOT EXISTS observations_status_idx        ON observations (status);
CREATE INDEX IF NOT EXISTS observations_taxon_id_idx      ON observations (taxon_id);
CREATE INDEX IF NOT EXISTS observations_place_id_idx      ON observations (place_id);
CREATE INDEX IF NOT EXISTS observations_phenophase_id_idx ON observations (phenophase_id);
CREATE INDEX IF NOT EXISTS observations_record_type_idx   ON observations (record_type);
CREATE INDEX IF NOT EXISTS observations_chunk_id_idx      ON observations (chunk_id);
CREATE INDEX IF NOT EXISTS observations_flags_gin         ON observations USING gin (flags);

CREATE INDEX IF NOT EXISTS observation_persons_person_idx ON observation_persons (person_id);
CREATE INDEX IF NOT EXISTS observation_edits_obs_idx      ON observation_edits (observation_id, created_at);
CREATE INDEX IF NOT EXISTS chunks_document_idx            ON chunks (document_id, ord);
CREATE INDEX IF NOT EXISTS sections_document_idx          ON sections (document_id);
CREATE INDEX IF NOT EXISTS taxon_names_taxon_idx          ON taxon_names (taxon_id);
CREATE INDEX IF NOT EXISTS place_names_place_idx          ON place_names (place_id);
